window.figureHTML = (name, caption, mode) => {
  const raw = window.ILLUSTRATIONS[name] || window.ILLUSTRATIONS.mouse;
  const svg = raw.replace(/\srole="img"/g, ' role="presentation"').replace(/\saria-label="[^"]*"/g, "");
  const cap = caption || "絵で見てください";
  const isHero = mode === "hero";
  const isCompact = mode === true || mode === "compact" || name === "done" || name === "compare";
  const badge = name === "done" ? "" : `<span class="pic-badge">絵で見る</span>`;
  const extra = `${isCompact ? " pic-compact" : ""}${isHero ? " pic-hero" : ""}${name === "compare" ? " pic-compare" : ""}`;
  return `<figure class="pic pic-easy${extra}">${badge}<div class="pic-svg" aria-hidden="true">${svg}</div><figcaption>${cap}</figcaption></figure>`;
};
